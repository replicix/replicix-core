//! Chunk identity and the self-describing chunk object format.
//!
//! * `chunk` - `ChunkHash` (blake3 of the plaintext, keyed in E2E mode)
//!   and `ChunkLayout` (fixed-size chunk arithmetic).
//! * `format` - the `CCH1` object (`encode_object`, `decode_object`,
//!   `StreamingDecoder`).
//! * `codec` - the append-only codec registry (raw, zstd, and with the
//!   `lz4` feature, lz4) and the bounded decompressors.
//! * `e2e` - the master key, its Argon2id wrap, purpose-separated key
//!   derivation and the XChaCha20-Poly1305 envelope.
//!
//! The bytes produced here are a stable on-disk and on-bucket format; the
//! golden tests under `tests/` pin them against fixtures generated by the
//! project they were extracted from.

pub mod chunk;
pub mod codec;
pub mod e2e;
pub mod env;
pub mod error;
pub mod format;

pub use chunk::{ChunkHash, ChunkLayout, ChunkSlice};
pub use codec::{Codec, CompressionSetting};
pub use e2e::{
    create_keyring_block, unlock, Argon2Params, E2eKeys, KeyDomain, KeyringBlock, ReplicixDomain,
    SharedE2eKeys,
};
pub use error::Error;
